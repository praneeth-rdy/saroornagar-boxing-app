/// Fixed component dimensions shared by the widget kit.
abstract final class AppSizes {
  /// Height of primary and secondary buttons.
  static const double controlHeight = 52;

  /// Smallest comfortable touch target on Android.
  static const double minTapTarget = 44;
  static const double listRowMinHeight = 64;
  static const double avatar = 40;

  /// Initials take this share of the avatar diameter.
  static const double avatarInitialsRatio = 0.38;
  static const double hairline = 1;
  static const double focusBorder = 1.5;
  static const double spinner = 20;
  static const double spinnerStroke = 2;
  static const double stateViewMaxWidth = 360;
}
